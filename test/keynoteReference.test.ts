function slide(name: string): Slide {
  const found = deck.slides.find((s) => s.name === name);
  if (!found) throw new Error(`reference.key has no slide named ${name}`);
  return found;
}

/** A slide's objects without the caption every slide carries top left. */
function objects(name: string): Any[] {
  return (slide(name).elements as Any[]).filter((el) =>
    !(el.type === 'text' && el.style?.['font-size'] === '28px'));
}

function ofType(name: string, type: string): Any[] {
  return objects(name).filter((el) => el.type === type);
}

function textNamed(name: string, words: string): Any {
  const found = ofType(name, 'text').find((el) => plain(el.html).includes(words));
  if (!found) throw new Error(`${name} has no text "${words}"`);
  return found;
}

function shapesFilled(name: string, fill: string): Any[] {
  return ofType(name, 'shape').filter((el) => el.fill === fill);
}

function plain(html: string): string {
  return html.replace(/<[^>]+>/g, '').replace(/&#x27;/g, "'").replace(/&amp;/g, '&');
}

const centre = (el: Any) => ({ x: el.x + el.w / 2, y: el.y + el.h / 2 });

/** Facts about written assets, read with PIL in the importer's own venv. */
function pixels(src: string, at: [number, number][]): { size: [number, number]; mode: string; at: number[][] } {
  const stdout = execFileSync(PYTHON, ['-c', [
    'import json, sys',
    'from PIL import Image',
    'image = Image.open(sys.argv[1])',
    'points = json.loads(sys.argv[2])',
    'print(json.dumps({"size": image.size, "mode": image.mode, "at": [list(image.convert("RGBA").getpixel(tuple(p))) for p in points]}))',
  ].join('\n'), join(out, 'deck', src), JSON.stringify(at)], { encoding: 'utf8' });
  return JSON.parse(stdout);
}

/** Whether an MP4/QuickTime file has its index (moov) before its media (mdat). */
function startsFast(file: string): boolean {
  const bytes = readFileSync(file);
  for (let at = 0; at + 8 <= bytes.length;) {
    let size = bytes.readUInt32BE(at);
    const type = bytes.toString('latin1', at + 4, at + 8);
    if (type === 'moov') return true;
    if (type === 'mdat') return false;
    if (size === 1) size = Number(bytes.readBigUInt64BE(at + 8));
    if (size < 8) return false;
    at += size;
  }
  return false;
}

